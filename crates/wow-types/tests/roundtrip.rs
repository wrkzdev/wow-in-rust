/// Statistics from one pass over a corpus index.
struct CorpusReport {
    checked: usize,
    with_signature: usize,
    verified_signatures: usize,
    by_version: BTreeMap<u8, usize>,
    failures: Vec<String>,
}

/// The committed HF 18+ boundary blocks.
///
/// From HF 18 every header carries a Schnorr signature over `sig_data`, made
/// with the coinbase output's one-time key (`specs/06` §4). Verifying those
/// against real blocks validates `sig_data`, the Schnorr verifier, point
/// decoding, the Merkle root and the parser **against consensus itself** — a
/// stronger check than `specs/15` §2.2's "compare against the C++
/// `get_sig_data` output", and one that needs no daemon at test time.
///
/// See `tests/corpus/blocks/hf18/README.md` for the heights and why they were
/// picked.
#[test]
fn hf18_header_signatures_verify() {
    let index = corpus_dir().join("blocks/hf18/index.tsv");
    let text = std::fs::read_to_string(&index)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", index.display()));
    let r = check_corpus(&text);

    eprintln!(
        "hf18 corpus: {} blocks, {} signed ({} verified), by major_version: {:?}",
        r.checked, r.with_signature, r.verified_signatures, r.by_version
    );
    assert!(
        r.failures.is_empty(),
        "{} of {} blocks failed:\n{}",
        r.failures.len(),
        r.checked,
        r.failures.join("\n")
    );
    assert_eq!(r.checked, 21, "the committed fixture holds 21 blocks");
    assert_eq!(
        r.verified_signatures, 20,
        "20 of the 21 are HF >= 18 and must have a verifying header signature"
    );
    // Both header-changing boundaries are represented.
    for v in [18u8, 19, 20] {
        assert!(
            r.by_version.contains_key(&v),
            "no HF {v} block in the fixture"
        );
    }
}

/// The real M1 gate: ~10,000 mainnet block blobs with their expected hashes.
///
/// Generated by `scripts/fetch-corpus.py`. Skipped with a clear message when
/// the corpus has not been generated, so a fresh checkout still builds.
#[test]
fn mainnet_block_corpus() {
    let dir = corpus_dir().join("blocks/mainnet");
    if !dir.exists() {
        eprintln!(
            "SKIP mainnet_block_corpus: {} not present.\n\
             Generate it with:  python scripts/fetch-corpus.py --daemon <host:port>\n\
             (specs/15 §2.2 -- the M1 gate is not closed until this runs.)",
            dir.display()
        );
        return;
    }

    let index = dir.join("index.tsv");
    let text = std::fs::read_to_string(&index)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", index.display()));
    let r = check_corpus(&text);

    eprintln!(
        "mainnet corpus: {} blocks, {} with a miner signature ({} verified)\n\
         by major_version: {:?}",
        r.checked, r.with_signature, r.verified_signatures, r.by_version
    );
    assert!(
        r.failures.is_empty(),
        "{} of {} blocks failed:\n{}",
        r.failures.len(),
        r.checked,
        r.failures.join("\n")
    );
    assert!(
        r.checked >= 1000,
        "corpus holds only {} blocks; specs/15 §2.2 wants ~10,000",
        r.checked
    );
}

/// One pass over an `index.tsv`, applying every check of `specs/15` §2.2.
fn check_corpus(text: &str) -> CorpusReport {
    let mut checked = 0usize;
    let mut with_signature = 0usize;
    let mut verified_signatures = 0usize;
    let mut by_version: BTreeMap<u8, usize> = BTreeMap::new();
    // Collected rather than asserted one at a time: over ~10k blocks the first
    // failing height is much less informative than the shape of the failures.
    let mut failures: Vec<String> = Vec::new();
    let note = |f: &mut Vec<String>, msg: String| {
        if f.len() < 25 {
            f.push(msg);
        }
    };

    for (lineno, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        // height \t block_id \t miner_tx_hash \t blob_hex [\t sig_data_hex]
        let f: Vec<&str> = line.split('\t').collect();
        assert!(
            f.len() >= 4,
            "index.tsv line {}: {} fields",
            lineno + 1,
            f.len()
        );
        let height: u64 = f[0].parse().expect("height");
        let want_id = f[1];
        let want_miner = f[2];
        let blob = hex::decode(f[3]).expect("blob hex");
        let what = format!("height {height}");

        let b = match Block::from_blob(&blob) {
            Ok(b) => b,
            Err(e) => {
                note(&mut failures, format!("{what}: parse failed: {e}"));
                continue;
            }
        };
        checked += 1;
        *by_version.entry(b.header.major_version).or_default() += 1;

        // serialize(parse(blob)) == blob
        let mut w = Writer::new();
        b.write(&mut w);
        if w.as_slice() != &blob[..] {
            note(&mut failures, format!("{what}: re-serialization differs"));
        }

        match b.block_id() {
            Some(id) if hex::encode(&id) == want_id => {}
            Some(id) => note(
                &mut failures,
                format!("{what}: block id {} != {want_id}", hex::encode(&id)),
            ),
            None => note(&mut failures, format!("{what}: no block id")),
        }

        // The coinbase hash, over its own slice of the block blob.
        let mut mw = Writer::new();
        b.miner_tx.write(&mut mw);
        let miner_blob = mw.into_vec();
        match transaction_hash_from_blob(&b.miner_tx, &miner_blob) {
            Some(h) if hex::encode(&h) == want_miner => {}
            Some(h) => note(
                &mut failures,
                format!("{what}: miner tx hash {} != {want_miner}", hex::encode(&h)),
            ),
            None => note(&mut failures, format!("{what}: no miner tx hash")),
        }

        // The Merkle root must be the value embedded in the hashing blob.
        if let (Some(hb), Some(root)) = (b.hashing_blob(), b.tx_tree_hash()) {
            let mut hw = Writer::new();
            b.header.write(&mut hw);
            let at = hw.len();
            if hb[at..at + 32] != root[..] {
                note(&mut failures, format!("{what}: Merkle root"));
            }
        } else {
            note(&mut failures, format!("{what}: no hashing blob"));
        }

        if b.header.has_miner_signature() {
            with_signature += 1;
            let sd = b.sig_data().expect("HF >= 18 always has sig_data");

            // The strongest check available without an instrumented C++ build,
            // and better than one: from HF 18 every header carries a Schnorr
            // signature over sig_data made with the coinbase output's one-time
            // key (`specs/06` §4). Verifying it against consensus validates the
            // sig_data construction, the Schnorr verifier and the parsing all
            // at once -- if any were wrong, real blocks would not verify.
            match b
                .miner_tx
                .prefix
                .vout
                .first()
                .and_then(|o| o.target.public_key())
            {
                Some(p) => {
                    if !wow_crypto::check_signature(&sd, &p, &b.header.signature) {
                        note(
                            &mut failures,
                            format!("{what}: header signature does not verify"),
                        );
                    } else {
                        verified_signatures += 1;
                    }
                }
                None => note(&mut failures, format!("{what}: no coinbase output key")),
            }
            // `specs/06` §4: exactly one coinbase output from HF 18.
            if b.miner_tx.prefix.vout.len() != 1 {
                note(
                    &mut failures,
                    format!("{what}: {} coinbase outputs", b.miner_tx.prefix.vout.len()),
                );
            }
            // sig_data must differ from the block id: the former zeroes the
            // signature, the latter does not.
            if Some(sd) == b.block_id() {
                note(&mut failures, format!("{what}: sig_data == block id"));
            }
            // vote is consensus-bounded from HF 18.
            if b.header.vote > 2 {
                note(&mut failures, format!("{what}: vote = {}", b.header.vote));
            }
            // Field 5, when present, is the C++ get_sig_data output.
            if let Some(want_sd) = f.get(4).filter(|s| !s.is_empty()) {
                if hex::encode(&sd) != *want_sd {
                    note(&mut failures, format!("{what}: sig_data"));
                }
            }
        }
    }

    CorpusReport {
        checked,
        with_signature,
        verified_signatures,
        by_version,
        failures,
    }
}
