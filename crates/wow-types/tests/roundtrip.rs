//! Round-trip and hash conformance — the M1 gate for `wow-types`.
//!
//! `specs/15-testing-and-conformance.md` §2.2:
//!
//! ```text
//! assert serialize(parse(block_blob)) == block_blob
//! assert block_id(parsed) == known hash
//! assert tx_hash(parsed.miner_tx) == known hash
//! assert merkle_root(parsed) == the value in the hashing blob
//! assert sig_data(parsed) == the C++ get_sig_data output   (HF >= 18 blocks)
//! ```
//!
//! "The re-serialization check catches non-canonical varints, missed
//! conditional fields and wrong array-length derivations in one line."
//!
//! The full gate wants ~10,000 mainnet blocks spread across all hard-fork eras.
//! That corpus is generated by `scripts/fetch-corpus.py` against a synced
//! daemon and dropped into `tests/corpus/blocks/mainnet/`; when it is absent
//! these tests fall back to what can be validated offline:
//!
//! * the genesis transaction of all three networks, from `specs/01` §2.2,
//! * the block and transaction blobs vendored from the reference tree's fuzz
//!   corpora and `tests/data/txs`,
//! * synthetic coverage of every structural variant the format admits.

use std::collections::BTreeMap;
use std::path::PathBuf;

use wow_crypto::hex;
use wow_serialize::binary::Writer;
use wow_types::block::Block;
use wow_types::hashes::transaction_hash_from_blob;
use wow_types::rct::RctType;
use wow_types::tx::Transaction;

fn corpus_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../tests/corpus")
}

/// `serialize(parse(blob)) == blob`, the single most valuable assertion here.
fn assert_block_roundtrips(blob: &[u8], what: &str) -> Block {
    let b = Block::from_blob(blob).unwrap_or_else(|e| panic!("{what}: parse failed: {e}"));
    let mut w = Writer::new();
    b.write(&mut w);
    assert_eq!(
        hex::encode(w.as_slice()),
        hex::encode(blob),
        "{what}: re-serialization differs"
    );
    b
}

fn assert_tx_roundtrips(blob: &[u8], what: &str) -> Transaction {
    let tx = Transaction::from_blob(blob).unwrap_or_else(|e| panic!("{what}: parse failed: {e}"));
    let mut w = Writer::new();
    tx.write(&mut w);
    assert_eq!(
        hex::encode(w.as_slice()),
        hex::encode(blob),
        "{what}: re-serialization differs"
    );

    // The recorded offsets must partition the blob exactly.
    assert!(
        tx.prefix_size <= tx.unprunable_size,
        "{what}: offsets inverted"
    );
    assert!(
        tx.unprunable_size <= blob.len(),
        "{what}: offsets past the blob"
    );
    tx
}

