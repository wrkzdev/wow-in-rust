fn read_corpus(sub: &str) -> Vec<(String, Vec<u8>)> {
    let dir = corpus_dir().join(sub);
    let mut out = Vec::new();
    let Ok(entries) = std::fs::read_dir(&dir) else {
        return out;
    };
    let mut paths: Vec<PathBuf> = entries
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.is_file() && p.extension().map_or(true, |e| e != "md"))
        .collect();
    paths.sort();
    for p in paths {
        if let Ok(b) = std::fs::read(&p) {
            out.push((p.file_name().unwrap().to_string_lossy().into_owned(), b));
        }
    }
    out
}

#[test]
fn reference_block_corpus_roundtrips() {
    let blocks = read_corpus("blocks");
    assert!(!blocks.is_empty(), "no block corpus found");
    for (name, blob) in blocks {
        let b = assert_block_roundtrips(&blob, &name);
        // Every parsed block must produce a block id and a Merkle root.
        assert!(b.block_id().is_some(), "{name}: no block id");
        assert!(b.tx_tree_hash().is_some(), "{name}: no Merkle root");
        // sig_data exists exactly when the header carries a signature.
        assert_eq!(
            b.sig_data().is_some(),
            b.header.has_miner_signature(),
            "{name}: sig_data presence"
        );
    }
}

#[test]
fn reference_transaction_corpus_roundtrips() {
    let txs = read_corpus("txs");
    assert!(!txs.is_empty(), "no transaction corpus found");
    for (name, blob) in txs {
        let tx = assert_tx_roundtrips(&blob, &name);
        assert!(
            transaction_hash_from_blob(&tx, &blob).is_some(),
            "{name}: no hash"
        );
    }
}

/// `foreign/bpp_tx_e89415.bin` is a **Monero** mainnet transaction that the
/// Wownero tree inherited as test data. It MUST NOT parse as Wownero.
///
/// The two chains number their RingCT types differently: Wownero inserted
/// `FullBulletproof = 3` and `SimpleBulletproof = 4`, shifting everything after
/// them, so Monero's `BulletproofPlus = 6` is Wownero's `Bulletproof2 = 6`. The
/// two layouts disagree and the blob runs out of input.
///
/// Worth pinning: silently accepting a foreign transaction because a type byte
/// happens to be in range is exactly how a cross-chain replay bug starts.
#[test]
fn a_monero_bulletproof_plus_tx_is_not_a_wownero_one() {
    let path = corpus_dir().join("foreign/bpp_tx_e89415.bin");
    let blob = std::fs::read(&path).expect("foreign/bpp_tx_e89415.bin");

    // The prefix format is shared, so it parses; the type byte follows it.
    let mut r = wow_serialize::binary::Reader::new(&blob);
    let prefix = wow_types::tx::TransactionPrefix::read(&mut r).expect("the prefix is shared");
    assert_eq!(prefix.version, 2);
    assert_eq!(prefix.vin.len(), 1);
    assert_eq!(prefix.vout.len(), 2);
    // Monero v15 outputs are tagged keys -- the same tag as Wownero HF 20.
    assert_eq!(prefix.vout[0].target.tag(), 0x03);

    let ty = blob[r.pos()];
    assert_eq!(ty, 6, "Monero BulletproofPlus is 6");
    assert_eq!(
        RctType::from_u8(ty).unwrap(),
        RctType::Bulletproof2,
        "the same byte means Bulletproof2 on Wownero"
    );

    assert!(
        Transaction::from_blob(&blob).is_err(),
        "a Monero BP+ transaction must not parse as Wownero"
    );
}

/// Every structural variant the format admits, round-tripped.
///
/// This stands in for the mainnet corpus on the axes a synthetic blob can
/// cover: the conditional header fields, both output target types, and each
/// RingCT type's `rctSigPrunable` layout. It does **not** substitute for real
/// chain data, which is the only thing that validates the hashes.
#[test]
fn synthetic_structural_coverage() {
    use wow_crypto::types::{EcPoint, EcScalar, KeyImage, PublicKey, Signature, ViewTag};
    use wow_types::block::BlockHeader;
    use wow_types::rct::{
        Bulletproof, BulletproofPlus, Clsag, EcdhInfo, MgSig, RangeSig, RctSignatures,
    };
    use wow_types::tx::{TransactionPrefix, TxIn, TxOut, TxOutTarget};

    let pt = |n: u8| EcPoint([n; 32]);
    let sc = |n: u8| EcScalar([n; 32]);

    for &ty in &[
        RctType::Null,
        RctType::Full,
        RctType::Simple,
        RctType::FullBulletproof,
        RctType::SimpleBulletproof,
        RctType::Bulletproof,
        RctType::Bulletproof2,
        RctType::Clsag,
        RctType::BulletproofPlus,
        RctType::BulletproofPlusFullCommit,
    ] {
        let inputs = 2usize;
        let outputs = 2usize;
        let ring = 22usize; // Wownero's fixed ring size at HF >= 9
        let mixin = ring - 1;

        let prefix = TransactionPrefix {
            version: 2,
            unlock_time: 0,
            vin: (0..inputs)
                .map(|i| TxIn::ToKey {
                    amount: 0,
                    key_offsets: (0..ring).map(|j| (j as u64) + 1).collect(),
                    k_image: KeyImage([(i as u8) + 1; 32]),
                })
                .collect(),
            vout: (0..outputs)
                .map(|i| TxOut {
                    amount: 0,
                    target: if i % 2 == 0 {
                        TxOutTarget::ToKey {
                            key: PublicKey([0x10 + i as u8; 32]),
                        }
                    } else {
                        // The HF 20 tagged form.
                        TxOutTarget::ToTaggedKey {
                            key: PublicKey([0x20 + i as u8; 32]),
                            view_tag: ViewTag(0x5a),
                        }
                    },
                })
                .collect(),
            extra: vec![0x01; 33],
        };

        let mut rv = RctSignatures {
            ty,
            txn_fee: if ty.is_null() { 0 } else { 123_456_789 },
            ..Default::default()
        };
        if !ty.is_null() {
            if ty == RctType::Simple {
                rv.pseudo_outs_base = (0..inputs).map(|i| pt(0x30 + i as u8)).collect();
            }
            rv.ecdh_info = (0..outputs)
                .map(|i| {
                    if ty.has_short_ecdh() {
                        let mut a = EcScalar::ZERO;
                        a.0[..8].copy_from_slice(&[i as u8; 8]);
                        EcdhInfo {
                            mask: EcScalar::ZERO,
                            amount: a,
                        }
                    } else {
                        EcdhInfo {
                            mask: sc(0x40 + i as u8),
                            amount: sc(0x50 + i as u8),
                        }
                    }
                })
                .collect();
            rv.out_pk = (0..outputs).map(|i| pt(0x60 + i as u8)).collect();

            let bp = |n: usize| Bulletproof {
                l: (0..n).map(|i| pt(0x70 + i as u8)).collect(),
                r: (0..n).map(|i| pt(0x80 + i as u8)).collect(),
                ..Default::default()
            };
            match ty {
                RctType::SimpleBulletproof | RctType::FullBulletproof => {
                    rv.bulletproofs = (0..outputs).map(|_| bp(7)).collect();
                }
                RctType::BulletproofPlus | RctType::BulletproofPlusFullCommit => {
                    rv.bulletproofs_plus = vec![BulletproofPlus {
                        l: (0..7).map(|i| pt(0x70 + i as u8)).collect(),
                        r: (0..7).map(|i| pt(0x80 + i as u8)).collect(),
                        ..Default::default()
                    }];
                }
                RctType::Bulletproof | RctType::Bulletproof2 | RctType::Clsag => {
                    rv.bulletproofs = vec![bp(7)];
                }
                RctType::Full | RctType::Simple => {
                    rv.range_sigs = (0..outputs).map(|_| RangeSig::default()).collect();
                }
                RctType::Null => {}
            }

            if ty.is_clsag() {
                rv.clsags = (0..inputs)
                    .map(|i| Clsag {
                        s: (0..=mixin).map(|j| sc(j as u8)).collect(),
                        c1: sc(0x90 + i as u8),
                        d: pt(0xa0 + i as u8),
                    })
                    .collect();
            } else {
                let simple_family = matches!(
                    ty,
                    RctType::Simple
                        | RctType::Bulletproof
                        | RctType::Bulletproof2
                        | RctType::SimpleBulletproof
                );
                let n_mg = if simple_family { inputs } else { 1 };
                let ss2 = if simple_family { 2 } else { inputs + 1 };
                rv.mgs = (0..n_mg)
                    .map(|i| MgSig {
                        ss: (0..=mixin)
                            .map(|_| (0..ss2).map(|k| sc(k as u8)).collect())
                            .collect(),
                        cc: sc(0xb0 + i as u8),
                    })
                    .collect();
            }

            if matches!(
                ty,
                RctType::SimpleBulletproof
                    | RctType::Bulletproof
                    | RctType::Bulletproof2
                    | RctType::Clsag
                    | RctType::BulletproofPlus
                    | RctType::BulletproofPlusFullCommit
            ) {
                rv.pseudo_outs = (0..inputs).map(|i| pt(0xc0 + i as u8)).collect();
            }
        }

        let tx = Transaction {
            prefix,
            signatures: Vec::new(),
            rct_signatures: rv,
            prefix_size: 0,
            unprunable_size: 0,
        };
        let mut w = Writer::new();
        tx.write(&mut w);
        let blob = w.into_vec();

        let parsed = assert_tx_roundtrips(&blob, &format!("synthetic {ty:?}"));
        assert_eq!(parsed.rct_signatures.ty, ty);
        assert_eq!(parsed.prefix, tx.prefix);
        assert_eq!(parsed.rct_signatures, tx.rct_signatures, "{ty:?}");
        assert!(
            transaction_hash_from_blob(&parsed, &blob).is_some(),
            "{ty:?}: no hash"
        );
    }

    // --- header variants: with and without signature + vote ---
    for major in [7u8, 17, 18, 20] {
        let header = BlockHeader {
            major_version: major,
            minor_version: major,
            timestamp: 1_700_000_000,
            prev_id: [0xab; 32],
            nonce: 0xdead_beef,
            signature: Signature {
                c: EcScalar([0x11; 32]),
                r: EcScalar([0x22; 32]),
            },
            vote: 2,
        };
        let miner_tx = Transaction::from_blob(&hex::decode(GENESIS_TX[0].1).unwrap()).unwrap();
        let block = Block {
            header: header.clone(),
            miner_tx,
            tx_hashes: (0u8..5).map(|i| [i; 32]).collect(),
        };
        let blob = block.to_blob();
        let parsed = assert_block_roundtrips(&blob, &format!("header v{major}"));

        if major >= 18 {
            assert!(parsed.header.has_miner_signature());
            assert_eq!(parsed.header.signature, header.signature);
            assert_eq!(parsed.header.vote, 2);
            assert!(parsed.sig_data().is_some());
            // Zeroing the signature must change sig_data while keeping vote.
            assert_ne!(parsed.sig_data().unwrap(), parsed.block_id().unwrap());
        } else {
            // Below HF 18 neither field is on the wire, so both read back as
            // zero whatever was set before serializing.
            assert!(!parsed.header.has_miner_signature());
            assert_eq!(parsed.header.signature, Signature::ZERO);
            assert_eq!(parsed.header.vote, 0);
            assert_eq!(parsed.sig_data(), None);
        }

        // The hashing blob always ends with varint(tx_count + 1).
        let hb = parsed.hashing_blob().unwrap();
        assert_eq!(*hb.last().unwrap(), 6, "5 tx hashes + the coinbase");
    }
}

