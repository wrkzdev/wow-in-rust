/// The 1024-bit state: `x[8][2]` of `u64`, read little-endian from the byte
/// form so the constants above can be used exactly as they appear in the C.
type State = [[u64; 2]; 8];

fn state_from_bytes(b: &[u8; 128]) -> State {
    let mut s = [[0u64; 2]; 8];
    for (i, row) in s.iter_mut().enumerate() {
        for (j, w) in row.iter_mut().enumerate() {
            let off = (i * 2 + j) * 8;
            *w = u64::from_le_bytes(b[off..off + 8].try_into().expect("8 bytes"));
        }
    }
    s
}

fn state_to_bytes(s: &State) -> [u8; 128] {
    let mut b = [0u8; 128];
    for (i, row) in s.iter().enumerate() {
        for (j, w) in row.iter().enumerate() {
            let off = (i * 2 + j) * 8;
            b[off..off + 8].copy_from_slice(&w.to_le_bytes());
        }
    }
    b
}

/// One round constant, as the two `u64`s the S-box layer consumes.
///
/// The C reads `rc[i]` and `rc[i + 2]` from the 32-byte constant viewed as four
/// `u64`s, so the two halves are 16 bytes apart.
fn constants(round: usize, i: usize) -> (u64, u64) {
    let rc = &ROUND_CONSTANTS[round];
    let c0 = u64::from_le_bytes(rc[i * 8..i * 8 + 8].try_into().expect("8 bytes"));
    let c1 = u64::from_le_bytes(
        rc[(i + 2) * 8..(i + 2) * 8 + 8]
            .try_into()
            .expect("8 bytes"),
    );
    (c0, c1)
}

/// Eight state words, named as the C's macros name them.
struct Words {
    m0: u64,
    m1: u64,
    m2: u64,
    m3: u64,
    m4: u64,
    m5: u64,
    m6: u64,
    m7: u64,
}

/// `SS` — two S-boxes in parallel, each choosing `S0` or `S1` per bit from the
/// round constant. The bitslicing is the algorithm here, not an optimisation.
fn ss(w: &mut Words, cc0: u64, cc1: u64) {
    w.m3 = !w.m3;
    w.m7 = !w.m7;
    w.m0 ^= !w.m2 & cc0;
    w.m4 ^= !w.m6 & cc1;
    let temp0 = cc0 ^ (w.m0 & w.m1);
    let temp1 = cc1 ^ (w.m4 & w.m5);
    w.m0 ^= w.m2 & w.m3;
    w.m4 ^= w.m6 & w.m7;
    w.m3 ^= !w.m1 & w.m2;
    w.m7 ^= !w.m5 & w.m6;
    w.m1 ^= w.m0 & w.m2;
    w.m5 ^= w.m4 & w.m6;
    w.m2 ^= w.m0 & !w.m3;
    w.m6 ^= w.m4 & !w.m7;
    w.m0 ^= w.m1 | w.m3;
    w.m4 ^= w.m5 | w.m7;
    w.m3 ^= w.m1 & w.m2;
    w.m7 ^= w.m5 & w.m6;
    w.m1 ^= temp0 & w.m0;
    w.m5 ^= temp1 & w.m4;
    w.m2 ^= temp0;
    w.m6 ^= temp1;
}

/// `L` — the MDS transform over the eight words.
fn l(w: &mut Words) {
    w.m4 ^= w.m1;
    w.m5 ^= w.m2;
    w.m6 ^= w.m0 ^ w.m3;
    w.m7 ^= w.m0;
    w.m0 ^= w.m5;
    w.m1 ^= w.m6;
    w.m2 ^= w.m4 ^ w.m7;
    w.m3 ^= w.m4;
}

/// Swap adjacent groups of `width` bits, the `SWAPn` macros.
fn swap(x: u64, width: u32) -> u64 {
    match width {
        1 => ((x & 0x5555_5555_5555_5555) << 1) | ((x >> 1) & 0x5555_5555_5555_5555),
        2 => ((x & 0x3333_3333_3333_3333) << 2) | ((x >> 2) & 0x3333_3333_3333_3333),
        4 => ((x & 0x0f0f_0f0f_0f0f_0f0f) << 4) | ((x >> 4) & 0x0f0f_0f0f_0f0f_0f0f),
        8 => ((x & 0x00ff_00ff_00ff_00ff) << 8) | ((x >> 8) & 0x00ff_00ff_00ff_00ff),
        16 => ((x & 0x0000_ffff_0000_ffff) << 16) | ((x >> 16) & 0x0000_ffff_0000_ffff),
        32 => x.rotate_left(32),
        other => unreachable!("swap width {other} is not one the reference uses"),
    }
}

/// One round: the S-box layer, the MDS transform, then an optional bit-swap.
#[allow(
    clippy::needless_range_loop,
    reason = "i is the second index of s[row][i], not the first"
)]
fn round(s: &mut State, r: usize, swap_width: Option<u32>) {
    for i in 0..2 {
        let (c0, c1) = constants(r, i);
        // The C passes the rows in the order 0, 2, 4, 6, 1, 3, 5, 7.
        let mut w = Words {
            m0: s[0][i],
            m1: s[2][i],
            m2: s[4][i],
            m3: s[6][i],
            m4: s[1][i],
            m5: s[3][i],
            m6: s[5][i],
            m7: s[7][i],
        };
        ss(&mut w, c0, c1);
        l(&mut w);

        s[0][i] = w.m0;
        s[2][i] = w.m1;
        s[4][i] = w.m2;
        s[6][i] = w.m3;
        s[1][i] = w.m4;
        s[3][i] = w.m5;
        s[5][i] = w.m6;
        s[7][i] = w.m7;

        if let Some(width) = swap_width {
            s[1][i] = swap(s[1][i], width);
            s[3][i] = swap(s[3][i], width);
            s[5][i] = swap(s[5][i], width);
            s[7][i] = swap(s[7][i], width);
        }
    }
}

/// `E8` — 42 rounds, in six groups of seven.
fn e8(s: &mut State) {
    for group in (0..42).step_by(7) {
        for (k, width) in [1u32, 2, 4, 8, 16, 32].into_iter().enumerate() {
            round(s, group + k, Some(width));
        }
        // The seventh round has no bit-swap. Instead the odd rows exchange
        // their two words, which is the 64-bit-granularity swap.
        round(s, group + 6, None);
        for i in (1..8).step_by(2) {
            s[i].swap(0, 1);
        }
    }
}

/// `F8` — the compression function. The message enters the first half of the
/// state and leaves through the second.
fn f8(s: &mut State, block: &[u8; 64]) {
    for i in 0..8 {
        let b = u64::from_le_bytes(block[i * 8..i * 8 + 8].try_into().expect("8 bytes"));
        s[i / 2][i % 2] ^= b;
    }
    e8(s);
    for i in 0..8 {
        let b = u64::from_le_bytes(block[i * 8..i * 8 + 8].try_into().expect("8 bytes"));
        s[4 + i / 2][i % 2] ^= b;
    }
}

/// JH-256 of `input`.
pub fn jh256(input: &[u8]) -> [u8; 32] {
    let mut s = state_from_bytes(&H0);

    let mut chunks = input.chunks_exact(64);
    for c in chunks.by_ref() {
        f8(&mut s, c.try_into().expect("chunks_exact(64)"));
    }

    let rest = chunks.remainder();
    let bitlen = (input.len() as u64) * 8;

    // JH's padding is **not** the usual "append the length if it still fits".
    // The length always gets a block to itself unless the message ended exactly
    // on a block boundary, in which case the `0x80` marker and the length share
    // one block. So a 1-byte message costs two compressions, same as a 63-byte
    // one.
    if rest.is_empty() {
        let mut buf = [0u8; 64];
        buf[0] = 0x80;
        buf[56..].copy_from_slice(&bitlen.to_be_bytes());
        f8(&mut s, &buf);
    } else {
        let mut buf = [0u8; 64];
        buf[..rest.len()].copy_from_slice(rest);
        buf[rest.len()] = 0x80;
        f8(&mut s, &buf);

        let mut tail = [0u8; 64];
        tail[56..].copy_from_slice(&bitlen.to_be_bytes());
        f8(&mut s, &tail);
    }

    // The digest is the last 32 bytes of the 1024-bit state.
    let bytes = state_to_bytes(&s);
    let mut out = [0u8; 32];
    out.copy_from_slice(&bytes[96..]);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The published JH-256 vector for the empty input.
    #[test]
    fn the_empty_input() {
        assert_eq!(
            crate::hex::encode(&jh256(b"")),
            "46e64619c18bb0a92a5e87185a47eef83ca747b8fcc8e1412921357e326df434"
        );
    }

    /// Every swap width is an involution, and 32 is a rotation.
    #[test]
    fn the_bit_swaps() {
        assert_eq!(swap(0xaaaa_aaaa_aaaa_aaaa, 1), 0x5555_5555_5555_5555);
        assert_eq!(swap(0x0000_0000_ffff_ffff, 32), 0xffff_ffff_0000_0000);
        for w in [1u32, 2, 4, 8, 16, 32] {
            let x = 0x0123_4567_89ab_cdef_u64;
            assert_eq!(swap(swap(x, w), w), x, "width {w}");
        }
    }

    /// The constants are the sizes the reference declares, and begin where it
    /// says they do.
    #[test]
    fn the_constants_are_complete() {
        assert_eq!(H0.len(), 128);
        assert_eq!(ROUND_CONSTANTS.len(), 42);
        assert_eq!(&H0[..4], &[0xeb, 0x98, 0xa3, 0x41]);
        assert_eq!(ROUND_CONSTANTS[0][0], 0x72);
        assert_eq!(ROUND_CONSTANTS[41][0], 0x35);
    }

    /// The state round-trips through its byte form, which the padding relies
    /// on.
    #[test]
    fn the_state_round_trips() {
        let s = state_from_bytes(&H0);
        assert_eq!(state_to_bytes(&s), H0);
    }

    /// A block-aligned message pads into one block; anything else into two.
    /// Getting this backwards still produces a plausible-looking digest, so it
    /// is worth pinning separately from the vectors.
    #[test]
    fn the_padding_boundaries() {
        // 64 bytes is block-aligned and 65 is not, so they cannot collide even
        // if the length field were dropped.
        assert_ne!(jh256(&[0u8; 64]), jh256(&[0u8; 65]));
        // Same block content, different declared length.
        assert_ne!(jh256(&[0u8; 1]), jh256(&[0u8; 2]));
        assert_ne!(jh256(&[0u8; 63]), jh256(&[0u8; 64]));
    }
}
